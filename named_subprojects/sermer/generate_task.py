from __future__ import annotations

import argparse
import random
import secrets
from pathlib import Path


def validate_dimensions(rows: int, cols: int) -> None:
    if not (1 <= rows <= 100 and 1 <= cols <= 100):
        raise ValueError("rows and columns must each be in the range 1..100")
    if not (2 <= rows * cols <= 10_000):
        raise ValueError("the board must contain between 2 and 10,000 cells")


def make_scramble(rows: int, cols: int, steps: int, rng: random.Random) -> tuple[list[int], int]:
    board = list(range(1, rows * cols)) + [0]
    blank = len(board) - 1
    previous_blank = -1

    def legal_neighbors(index: int) -> list[int]:
        row, col = divmod(index, cols)
        result: list[int] = []
        if row > 0:
            result.append(index - cols)
        if row + 1 < rows:
            result.append(index + cols)
        if col > 0:
            result.append(index - 1)
        if col + 1 < cols:
            result.append(index + 1)
        return result

    actual_steps = 0
    for _ in range(steps):
        choices = legal_neighbors(blank)
        # Avoid immediately undoing the last move when another option exists.
        if previous_blank in choices and len(choices) > 1:
            choices.remove(previous_blank)
        nxt = rng.choice(choices)
        board[blank], board[nxt] = board[nxt], board[blank]
        previous_blank, blank = blank, nxt
        actual_steps += 1

    # Keep generated test cases nontrivial when the random walk happens to return
    # to the goal (possible on short or narrow boards).
    if steps > 0 and board[-1] == 0 and all(value == i + 1 for i, value in enumerate(board[:-1])):
        choices = legal_neighbors(blank)
        nxt = rng.choice(choices)
        board[blank], board[nxt] = board[nxt], board[blank]
        actual_steps += 1

    return board, actual_steps


def render_task(rows: int, cols: int, board: list[int], costs: tuple[int, int, int, int],
                seed: int, scramble_steps: int) -> str:
    lines = ["-- Generated by generate_task.py",
             f"-- seed={seed}; requested_scramble_steps={scramble_steps}",
             "DATA", f"SIZE {rows} {cols}"]
    for row in range(rows):
        row_values = board[row * cols:(row + 1) * cols]
        lines.append(" ".join("=" if value == 0 else str(value) for value in row_values))
    lines += ["/", "COST", " ".join(map(str, costs)), "/"]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Create a reachable sliding-puzzle task in the DATA/COST text format.")
    parser.add_argument("rows", type=int, help="number of rows (1..100)")
    parser.add_argument("cols", type=int, help="number of columns (1..100)")
    parser.add_argument("-o", "--output", type=Path,
                        help="output .txt path (default: task_NxM.txt in the current directory)")
    parser.add_argument("--steps", type=int, default=100,
                        help="number of random legal scramble moves (default: 100)")
    parser.add_argument("--seed", type=int,
                        help="random seed, for reproducible instances (default: generated automatically)")
    parser.add_argument("--costs", nargs=4, type=int, metavar=("U", "D", "L", "R"),
                        default=(1, 1, 1, 1),
                        help="nonnegative move costs in U D L R order (default: 1 1 1 1)")
    args = parser.parse_args()

    try:
        validate_dimensions(args.rows, args.cols)
        if args.steps < 0:
            raise ValueError("--steps must be nonnegative")
        if any(cost < 0 for cost in args.costs):
            raise ValueError("move costs must be nonnegative")

        seed = args.seed if args.seed is not None else secrets.randbits(32)
        rng = random.Random(seed)
        board, actual_steps = make_scramble(args.rows, args.cols, args.steps, rng)
        output = args.output or Path(f"task_{args.rows}x{args.cols}.txt")
        if output.suffix.lower() != ".txt":
            raise ValueError("output file must have a .txt extension")
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(render_task(args.rows, args.cols, board, tuple(args.costs),
                                      seed, args.steps), encoding="utf-8")

        print(f"Created: {output}")
        print(f"Size: {args.rows} x {args.cols} ({args.rows * args.cols} cells)")
        print(f"Scramble moves: {actual_steps} (requested {args.steps})")
        print(f"Costs U D L R: {' '.join(map(str, args.costs))}")
        print(f"Seed: {seed}")
        return 0
    except (OSError, ValueError) as error:
        parser.error(str(error))
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
