#!/usr/bin/env python3
"""Reproducible integration tests for the C++ row-by-row solver."""
from __future__ import annotations
import random
import subprocess
import sys
from support import binary_path
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = sorted((ROOT / "src").glob("*.cpp"))


def make_scramble(rows: int, cols: int, steps: int, rng: random.Random) -> list[int]:
    board = list(range(1, rows * cols)) + [0]
    blank = len(board) - 1
    previous_blank = -1
    for _ in range(steps):
        r, c = divmod(blank, cols)
        choices = []
        if r > 0: choices.append(blank - cols)
        if r + 1 < rows: choices.append(blank + cols)
        if c > 0: choices.append(blank - 1)
        if c + 1 < cols: choices.append(blank + 1)
        if previous_blank in choices and len(choices) > 1:
            choices.remove(previous_blank)
        nxt = rng.choice(choices)
        board[blank], board[nxt] = board[nxt], board[blank]
        previous_blank, blank = blank, nxt
    return board


def write_input(path: Path, rows: int, cols: int, board: list[int]) -> None:
    with path.open("w", encoding="utf-8") as f:
        f.write(f"DATA\nSIZE {rows} {cols}\n")
        for r in range(rows):
            vals = board[r * cols:(r + 1) * cols]
            f.write(" ".join("=" if x == 0 else str(x) for x in vals) + "\n")
        f.write("/\nCOST\n2 3 1 4\n/\n")


def expected_goal(rows: int, cols: int) -> str:
    vals = list(range(1, rows * cols)) + [0]
    lines = []
    for r in range(rows):
        lines.append(" ".join("=" if x == 0 else str(x) for x in vals[r * cols:(r + 1) * cols]))
    return "\n".join(lines)


def run_case(binary: Path, temp: Path, rows: int, cols: int, steps: int, seed: int) -> tuple[int, float]:
    board = make_scramble(rows, cols, steps, random.Random(seed))
    inp = temp / f"input_{rows}x{cols}_{seed}.txt"
    out = temp / f"output_{rows}x{cols}_{seed}.txt"
    checked = temp / f"checked_{rows}x{cols}_{seed}.txt"
    write_input(inp, rows, cols, board)
    solved = subprocess.run([str(binary), str(inp), str(out), "--algorithm", "rowbyrow"],
                            text=True, capture_output=True, timeout=60)
    if solved.returncode != 0:
        raise AssertionError(f"rowbyrow failed for {rows}x{cols}: {solved.stderr}\n{solved.stdout}")
    summary = solved.stdout.strip().splitlines()[0]
    if "RESULT: SOLVED" not in summary:
        raise AssertionError(f"missing success summary: {summary}")
    verified = subprocess.run([str(binary), str(out), str(checked)], text=True,
                              capture_output=True, timeout=60)
    if verified.returncode != 0 or "CHECK: VALID" not in verified.stdout:
        raise AssertionError(f"generated ORDER did not validate: {verified.stderr}\n{verified.stdout[:1000]}")
    placed = f"placed={rows * cols - 1}"
    if placed not in verified.stdout:
        raise AssertionError(f"not all tiles placed: {verified.stdout[:500]}")
    # The checker prints the final board; compare exact rows against the goal.
    marker = "Final board:\n"
    if marker not in verified.stdout:
        raise AssertionError("checker omitted final board")
    actual = verified.stdout.split(marker, 1)[1].strip()
    if actual != expected_goal(rows, cols):
        raise AssertionError(f"final board differs from goal on {rows}x{cols}")
    return len(out.read_text(encoding="utf-8").splitlines()), float(summary.split("seconds=")[-1])


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="pyatnashki_test_") as tmpdir:
        temp = Path(tmpdir)
        binary = binary_path()
        cases = []
        seed = 101
        for rows, cols in [(2, 3), (3, 2), (3, 4), (4, 3), (4, 5), (5, 4),
                           (2, 7), (7, 2), (3, 10), (10, 3), (5, 6), (6, 5)]:
            for _ in range(3):
                cases.append((rows, cols, 80, seed))
                seed += 1
        # Near-maximum legal dimensions; still a reachable board generated by legal moves.
        cases.extend([(100, 99, 1500, 20261023), (99, 100, 1500, 20261024),
                      (100, 2, 1500, 20261025), (2, 100, 1500, 20261026)])
        for idx, (rows, cols, steps, case_seed) in enumerate(cases, 1):
            _, elapsed = run_case(binary, temp, rows, cols, steps, case_seed)
            print(f"[{idx:02d}/{len(cases)}] OK {rows}x{cols}, scramble={steps}, solver={elapsed:.3f}s")
        print(f"PASS: {len(cases)} integration cases; every ORDER validated and every final board solved.")


if __name__ == "__main__":
    main()
